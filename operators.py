#1. rithmetic Operators - Simple calculations.
x = 7
y = 6

print(x + y)
print(x - y)
print(x * y)
print(x / y)
print(x % y) #Modulus - Returns remainder after division

#2. Comparison Operators - Used to compare values.
num1 = 45
num2 = 54

print(num1 < num2)
print(num1 > num2)
print(num1 <= num2)
print(num1 >= num2)
print(num1 == num2) #Equal to.
print(num1 != num2) #Not equal to.

#3. Assignment Operators - Assign/ Store values in a variable.
number = 15
print(number)

#Operator Precedence - order in which operations get executed.
number += 5
print(number) #Output is 20 since it is displayed as 15+5.

#4. Logical Operators - and, or, not.
print(100 == 30 and 60 <200)
print(100 == 30 or 60 <200)
print( not(100 == 30 or 60 <200) )
